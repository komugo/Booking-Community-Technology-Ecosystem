export type Fee = { min: number; max?: number; from?: boolean; plus?: boolean };

export const LOCALES: Locale[] = ["en", "ms"];

export const href = (l: Locale, p = "/") => (l === "ms" ? (p === "/" ? "/ms" : `/ms${p}`) : p);

export const alternates = (p: string): Record<Locale, string> => ({ en: href("en", p), ms: href("ms", p) });

const n = (v: number) => v.toLocaleString("en-MY");

export function rm(l: Locale, f: Fee, inline = false) {
  const range = f.max ? `RM${n(f.min)}–${n(f.max)}` : `RM${n(f.min)}`;
  const from = inline ? t[l].from.toLowerCase() : t[l].from;
  return `${f.from ? from + " " : ""}${range}${f.plus ? "+" : ""}`;
}

