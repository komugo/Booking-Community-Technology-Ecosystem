export const t = { en, ms };

const KEY = "ops:locale";
const initial = (): Locale => {
  const saved = readLocal<Locale>(KEY);
  return saved === "en" || saved === "ms" ? saved : navigator.language.startsWith("ms") ? "ms" : "en";
};
const locale = store<Locale>(initial());

export function setLocale(l: Locale) {
  writeLocal(KEY, l);
  locale.set(l);
}

export function useT() {
  const l = locale.use();
  return { t: t[l], l };
}

export const named = (x: Named, l: Locale) => (l === "ms" ? x.nameMs : x.nameEn);

const fmt = (l: Locale, o: Intl.DateTimeFormatOptions) => new Intl.DateTimeFormat(l === "ms" ? "ms-MY" : "en-MY", { timeZone: TZ, ...o });
export const time = (ms: number, l: Locale) => fmt(l, { hour: "2-digit", minute: "2-digit", hourCycle: "h23" }).format(ms);
export const day = (ms: number, l: Locale) => fmt(l, { weekday: "short", day: "numeric", month: "short" }).format(ms);
export const dateLong = (ms: number, l: Locale) => fmt(l, { day: "numeric", month: "short", year: "numeric" }).format(ms);
export const monthLong = (month: string, l: Locale) => fmt(l, { month: "long", year: "numeric" }).format(Date.parse(`${month}-01T00:00:00+08:00`));

export function errorText(e: unknown, d: Dict) {
  const code = (e as { code?: string }).code ?? "error";
  if (code === "otp_invalid") return d.errors.otp_invalid(Number((e as { params?: { triesLeft?: number } }).params?.triesLeft ?? 0));
  const msg = d.errors[code as Exclude<keyof Dict["errors"], "otp_invalid">];
  return typeof msg === "string" ? msg : d.errors.error;
}
